/**
 * Get status details with fallback for unknown status
 */
export function getStatusConfig(status) {
  return (
    REPAIR_STATUS_CONFIG[status] || {
      label: status?.replace(/_/g, ' ') || 'Unknown',
      shortLabel: status?.replace(/_/g, ' ') || 'Unknown',
      stageGroup: 'diagnosis',
      stageIndex: 0,
      badgeClass: 'badge-gray',
      icon: FileEdit,
      color: 'gray',
      description: 'Status update.',
      requiredAction: { owner: 'No action required.', technician: '', admin: '' },
      contextualHelp: '',
      primaryAction: null,
      secondaryAction: null,
      overflowActions: [],
    }
  );
}

/**
 * Calculate stage progress for stepper (0 to 4)
 */
export function getStageProgress(status) {
  const cfg = getStatusConfig(status);
  return cfg.stageIndex ?? 0;
}
